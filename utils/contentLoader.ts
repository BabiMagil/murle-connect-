// FORMAT ARTICLE
// ===============================


function formatArticle(
  item:any,
  index:number,
  category:string
){

  return {

    ...item,


    id:String(
      item.id ??
      item.slug ??
      `${category}-${index + 1}`
    ),


    slug:
      item.slug ??
      String(
        item.id ??
        `${category}-${index + 1}`
      ),


    category,


    title:
      item.title ??
      "Untitled Article",


    subtitle:
      item.subtitle ??
      "",


    body:
      item.body ??
      item.content ??
      item.description ??
      item.text ??
      item.meaning ??
      "",


    summary:
      item.summary ??
      item.description ??
      "",


    image:
      item.image ??
      null,


    // proverb support

    murle:
      item.murle ??
      item.proverb ??
      item.original ??
      "",


    english:
      item.english ??
      item.translation ??
      item.meaning ??
      "",


    explanation:
      item.explanation ??
      item.meaning ??
      "",


    author:
      item.author ??
      "Murle Connect",


    featured:
      item.featured ??
      false

  };

}



