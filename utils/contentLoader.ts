// ===============================
// SEARCH
// ===============================


export function searchArticles(
query:string
){

const q =

query
.toLowerCase()
.trim();



return allArticles.filter(

article => {


const title =

String(article.title ?? "")
.toLowerCase();



const body =

String(article.body ?? "")
.toLowerCase();



const summary =

String(article.summary ?? "")
.toLowerCase();



return (

title.includes(q)

||

body.includes(q)

||

summary.includes(q)

);


}

);


}




